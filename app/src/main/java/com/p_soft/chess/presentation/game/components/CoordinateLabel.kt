@Composable
fun CoordinateLabel(text: String) {
    Box(
        modifier = Modifier
            .width(20.dp)
            .fillMaxHeight()
            .background(MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f)),
